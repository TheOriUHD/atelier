/**
 * The docs' CLI reference (apps/docs/src/content/docs/reference/cli.md) is made from the command line's own tables:
 * `pnpm docs:generate` writes it, and this fails while it is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, it } from 'vitest';
import { COMMAND_HELP, FLAGS } from './args.ts';
import { COMMANDS } from './tui/commands.ts';
import { KEY_HELP } from './tui/keys.ts';

const FILE = join(import.meta.dirname, '../../docs/src/content/docs/reference/cli.md');
const cell = (s: string) => s.replace(/\|/g, '\\|');

export function reference(): string {
  return [
    '---',
    'title: CLI reference',
    'description: "Every command, option, slash command and key of Atelier CLI. Generated from the code."',
    'editUrl: false',
    '---',
    '',
    '<!-- Generated by apps/cli/src/reference.test.ts (pnpm docs:generate). Edit the tables in apps/cli/src, not this page. -->',
    '',
    'How to install and set it up: [Atelier CLI](/cli/).',
    '',
    '## Commands',
    '',
    '| Command | What it does |',
    '|---|---|',
    ...COMMAND_HELP.map(([c, h]) => `| \`${cell(c)}\` | ${cell(h)} |`),
    '',
    '## Options',
    '',
    '| Option | What it does |',
    '|---|---|',
    ...FLAGS.filter((f) => f.help).map((f) => `| ${f.short ? `\`-${f.short}\`, ` : ''}\`--${f.name}${f.value ? ` <${f.value}>` : ''}\` | ${cell(f.help)} |`),
    '',
    '## Slash commands',
    '',
    'Skills and commands of the folder and your account are listed in the same menu and run as they do in the app.',
    '',
    '| Command | What it does |',
    '|---|---|',
    ...COMMANDS.filter((c) => !c.hidden).map((c) => `| \`/${c.name}${c.argumentHint ? ` ${cell(c.argumentHint)}` : ''}\`${c.aliases?.length ? ` (${c.aliases.map((a) => `\`/${a}\``).join(', ')})` : ''} | ${cell(c.description)} |`),
    '',
    '## Keys',
    '',
    '| Key | What it does |',
    '|---|---|',
    ...KEY_HELP.map(([k, h]) => `| ${cell(k)} | ${cell(h)} |`),
    '',
    '## Environment variables',
    '',
    '| Variable | What it does |',
    '|---|---|',
    '| `ATELIER_CLI_DIR` | Where the terminal app keeps its settings and data (default `~/.atelier/cli`). |',
    '| `ATELIER_SERVER` | The server to use for this run, as `--server`. |',
    '| `ATELIER_TOKEN` | A sign-in to use instead of the stored one (CI); `atelier token` prints yours. Not kept. |',
    '| `ATELIER_CLI_CREDENTIALS` | `file`: keep secrets in `credentials.json` instead of the system’s store. |',
    '| `ATELIER_NO_UPDATE_CHECK` | Set: no daily look for a newer version. |',
    '| `ATELIER_NO_BROWSER` | Set: never open a browser (it says the link instead). |',
    '| `ATELIER_RUNNER_DIR` | Use the runner builds in this folder. |',
    '| `NO_COLOR`, `FORCE_COLOR` | No colour; or this many colours (1: 16, 2: 256, 3: millions). |',
    '| `VISUAL`, `EDITOR` | The editor Ctrl+G opens. |',
    '',
  ].join('\n');
}

it('the reference page is current', () => {
  const text = reference();
  if (process.env.UPDATE_DOCS) writeFileSync(FILE, text);
  expect(readFileSync(FILE, 'utf8')).toBe(text);
});
