// Embeds prompts/**/*.md into src/prompts/templates.gen.ts (defaults; users override in ~/.atelier/prompts/).
// Keys are paths without the extension: `code.full`, `fragments/search.full`, `notes/plan-on`.
import { fileURLToPath } from 'node:url';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = join(root, 'prompts');
const names = (await readdir(dir, { recursive: true })).filter((f) => f.endsWith('.md')).map((f) => f.split('\\').join('/')).sort();
const entries = {};
for (const f of names) entries[f.replace(/\.md$/, '')] = await readFile(join(dir, f), 'utf8');
await writeFile(
  join(root, 'src/prompts/templates.gen.ts'),
  `// GENERATED by scripts/embed-prompts.mjs from prompts/**/*.md. Do not edit.\nexport const defaultTemplates: Record<string, string> = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(`embedded ${names.length} prompt templates`);
