// Embeds drizzle/*/migration.sql into src/store/migrations.gen.ts so bundled apps need no migration folder.
import { fileURLToPath } from 'node:url';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const dirs = (await readdir(join(root, 'drizzle'), { withFileTypes: true })).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const entries = [];
for (const name of dirs) {
  const sql = await readFile(join(root, 'drizzle', name, 'migration.sql'), 'utf8');
  entries.push({ name, statements: sql.split('--> statement-breakpoint').map((s) => s.trim()).filter(Boolean) });
}
const out = `// GENERATED by scripts/embed-migrations.mjs from drizzle/. Do not edit.\nexport const migrations: { name: string; statements: string[] }[] = ${JSON.stringify(entries, null, 2)};\n`;
await writeFile(join(root, 'src/store/migrations.gen.ts'), out);
console.log(`embedded ${entries.length} migrations`);
