/**
 * Generates the app theme from design/tokens/tokens.json:
 *   packages/ui/theme/tokens.css    CSS variables (--at-*) for light, dark and system
 *   packages/ui/theme/tailwind.css  Tailwind v4 @theme mapping onto those variables
 *   packages/ui/theme/colors.json   resolved color values per theme, for code that needs literals (syntax themes)
 *   design/tokens/tokens.schema.json
 * Deterministic: same input, byte-identical output.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { TokensSchema, colorRoles, type Tokens } from './lib/tokens-schema.ts';

const designRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(designRoot, '..');
const themeDir = join(repoRoot, 'packages/ui/theme');

const tokens: Tokens = TokensSchema.parse(JSON.parse(await readFile(join(designRoot, 'tokens/tokens.json'), 'utf8')));

/** CSS family names of the bundled (Fontsource) fonts. */
const cssFamily: Record<string, string> = {
  Inter: '"Inter Variable"',
  'Source Serif 4': '"Source Serif 4 Variable"',
  'JetBrains Mono': '"JetBrains Mono Variable"',
  OpenDyslexic: '"OpenDyslexic"',
  'system-ui': 'system-ui',
};
/**
 * The weight tokens are on a light variable axis (regular = 360). Inter at the same nominal value
 * reads thinner, so bundled-font weights are offset to give the intended stroke weight.
 */
const weightOffset = 40;

/** Tailwind-facing names for color roles (utilities read as bg-surface, text-fg-muted, border-line …). */
const twColorName = (role: string): string =>
  ({
    background: 'bg',
    'background-sunken': 'bg-sunken',
    'surface-raised': 'raised',
    'surface-popover': 'popover',
    border: 'line',
    'border-subtle': 'line-subtle',
    'border-strong': 'line-strong',
    'border-stronger': 'line-stronger',
    'text-primary': 'fg',
    'text-secondary': 'fg-secondary',
    'text-muted': 'fg-muted',
    'text-disabled': 'fg-disabled',
  })[role] ?? role;

// `text-<name>` must mean one thing: a type role named like a color role would make Tailwind
// resolve the utility to the color (e.g. text in the bubble's own background color).
const clashes = Object.keys(tokens.type).filter((name) => colorRoles.some((r) => twColorName(r) === name));
if (clashes.length > 0) throw new Error(`Type roles clash with color names: ${clashes.join(', ')}. Rename them in tokens.json.`);

const px = (n: number) => (n === 0 ? '0' : `${n}px`);
const header = '/* GENERATED by design/scripts/build-theme.ts from design/tokens/tokens.json. Do not edit. */\n';
const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;

function colorLines(theme: 'light' | 'dark'): string[] {
  const c = tokens.color[theme];
  return [
    `color-scheme: ${theme};`,
    ...colorRoles.map((r) => `--at-color-${r}: ${c[r]};`),
    ...Object.entries(tokens.shadow[theme]).map(([k, v]) => `--at-shadow-${k}: ${v};`),
  ];
}

function fontStack(key: keyof Tokens['font']): string {
  const f = tokens.font[key];
  return `${cssFamily[f.family] ?? `"${f.family}"`}, ${f.fallback}`;
}

function staticLines(): string[] {
  const lines: string[] = [];
  for (const key of ['sans', 'serif', 'mono', 'dyslexic', 'system'] as const) lines.push(`--at-font-${key}: ${fontStack(key)};`);
  // User-selectable roles (Settings › General › Chat font, Settings › Code › Interface/Code font).
  lines.push('--at-font-ui: var(--at-font-sans);', '--at-font-chat: var(--at-font-serif);', '--at-font-code: var(--at-font-mono);');
  for (const [name, w] of Object.entries(tokens.fontWeight)) lines.push(`--at-weight-${name}: ${w + weightOffset};`);
  for (const [name, t] of Object.entries(tokens.type)) {
    const size = typeof t.size === 'number' ? px(t.size) : t.size;
    const leading = typeof t.size === 'number' ? px(t.lineHeight) : String(t.lineHeight);
    lines.push(
      `--at-text-${name}-size: ${size};`,
      `--at-text-${name}-leading: ${leading};`,
      `--at-text-${name}-weight: var(--at-weight-${t.weight});`,
      `--at-text-${name}-tracking: ${t.tracking === 0 ? '0' : `${t.tracking}px`};`,
      `--at-text-${name}-family: var(--at-font-${t.family === 'serif' ? 'chat' : t.family === 'mono' ? 'code' : 'ui'});`,
    );
  }
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(`--at-radius-${k}: ${v === 9999 ? '9999px' : px(v)};`);
  for (const [group, values] of Object.entries(tokens.size)) {
    for (const [k, v] of Object.entries(values)) {
      if (Array.isArray(v)) lines.push(`--at-size-${group}-${k}-w: ${px(v[0])};`, `--at-size-${group}-${k}-h: ${px(v[1])};`);
      else lines.push(`--at-size-${group}-${k}: ${px(v as number)};`);
    }
  }
  for (const [k, v] of Object.entries(tokens.motion.duration)) lines.push(`--at-duration-${k}: ${v}ms;`);
  for (const [k, v] of Object.entries(tokens.motion.easing)) lines.push(`--at-ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.layout)) {
    if (typeof v === 'number') lines.push(`--at-layout-${k}: ${px(v)};`);
    else if (Array.isArray(v)) lines.push(`--at-layout-${k}-w: ${px(v[0])};`, `--at-layout-${k}-h: ${px(v[1])};`);
    else if (v && typeof v === 'object') {
      for (const [sk, sv] of Object.entries(v)) if (typeof sv === 'number') lines.push(`--at-layout-${k}-${sk}: ${k === 'z' ? sv : px(sv)};`);
    }
  }
  lines.push('--at-transcript-max: var(--at-layout-transcript-width-medium);');
  return lines;
}

const tw = tokens.layout['transcript-width'] as Record<string, number>;
const tokensCss =
  header +
  block(':root', [...staticLines(), ...colorLines('light')]) +
  '\n' +
  block(':root[data-theme="dark"]', colorLines('dark')) +
  '\n@media (prefers-color-scheme: dark) {\n' +
  block(':root[data-theme="system"]', colorLines('dark')).replace(/^/gm, '  ').trimEnd() +
  '\n}\n\n' +
  '/* Appearance settings, applied as attributes on <html>. */\n' +
  block(':root[data-chat-font="sans"]', ['--at-font-chat: var(--at-font-sans);']) +
  block(':root[data-chat-font="system"]', ['--at-font-chat: var(--at-font-system);']) +
  block(':root[data-chat-font="dyslexic"]', ['--at-font-chat: var(--at-font-dyslexic);']) +
  block(':root[data-ui-font="system"]', ['--at-font-ui: var(--at-font-system);']) +
  block(':root[data-ui-font="dyslexic"]', ['--at-font-ui: var(--at-font-dyslexic);']) +
  block(':root[data-text-size="s"]', ['--at-text-prose-size: var(--at-text-prose-sm-size);', '--at-text-prose-leading: var(--at-text-prose-sm-leading);']) +
  block(':root[data-text-size="l"]', ['--at-text-prose-size: var(--at-text-prose-lg-size);', '--at-text-prose-leading: var(--at-text-prose-lg-leading);']) +
  Object.keys(tw)
    .filter((k) => typeof tw[k] === 'number')
    .map((k) => block(`:root[data-transcript-width="${k}"]`, [`--at-transcript-max: var(--at-layout-transcript-width-${k});`]))
    .join('') +
  block('::selection', ['background: var(--at-color-selection);']);

const twLines: string[] = ['--color-*: initial;', '--color-transparent: transparent;', '--color-current: currentColor;'];
for (const r of colorRoles) twLines.push(`--color-${twColorName(r)}: var(--at-color-${r});`);
twLines.push(
  '--font-*: initial;',
  '--font-sans: var(--at-font-ui);',
  '--font-chat: var(--at-font-chat);',
  '--font-serif: var(--at-font-serif);',
  '--font-mono: var(--at-font-code);',
  '--font-weight-regular: var(--at-weight-regular);',
  '--font-weight-medium: var(--at-weight-medium);',
  '--font-weight-semibold: var(--at-weight-semibold);',
  '--font-weight-bold: var(--at-weight-bold);',
  '--text-*: initial;',
);
for (const name of Object.keys(tokens.type)) {
  twLines.push(
    `--text-${name}: var(--at-text-${name}-size);`,
    `--text-${name}--line-height: var(--at-text-${name}-leading);`,
    `--text-${name}--font-weight: var(--at-text-${name}-weight);`,
    `--text-${name}--letter-spacing: var(--at-text-${name}-tracking);`,
  );
}
twLines.push('--radius-*: initial;');
for (const k of Object.keys(tokens.radius)) twLines.push(`--radius-${k}: var(--at-radius-${k});`);
twLines.push('--shadow-*: initial;');
for (const k of Object.keys(tokens.shadow.light)) twLines.push(`--shadow-${k}: var(--at-shadow-${k});`);
twLines.push('--ease-*: initial;');
for (const k of Object.keys(tokens.motion.easing)) twLines.push(`--ease-${k}: var(--at-ease-${k});`);
twLines.push(`--spacing: ${px(tokens.space['1']!)};`);

const tailwindCss =
  header +
  '@import "./tokens.css";\n\n' +
  '@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));\n\n' +
  block('@theme inline', twLines);

const colorsJson = JSON.stringify(
  Object.fromEntries((['light', 'dark'] as const).map((t) => [t, Object.fromEntries(colorRoles.map((r) => [r, tokens.color[t][r]]))])),
  null,
  2,
) + '\n';
const schemaJson = JSON.stringify(z.toJSONSchema(TokensSchema, { io: 'input' }), null, 2) + '\n';

await mkdir(themeDir, { recursive: true });
await writeFile(join(themeDir, 'tokens.css'), tokensCss);
await writeFile(join(themeDir, 'tailwind.css'), tailwindCss);
await writeFile(join(themeDir, 'colors.json'), colorsJson);
await writeFile(join(designRoot, 'tokens/tokens.schema.json'), schemaJson);
console.log(`theme: ${colorRoles.length} color roles x 2 themes, ${Object.keys(tokens.type).length} type roles -> packages/ui/theme/`);
