type fakeResolver struct {
	folders   map[string]string
	shortcuts map[string]string
}

func (f fakeResolver) KnownFolder(guid string) (string, bool) {
	p, ok := f.folders[strings.ToUpper(guid)]
	return p, ok
}

func (f fakeResolver) Shortcut(name string) (string, bool) {
	p, ok := f.shortcuts[strings.ToLower(name)]
	return p, ok
}

var resolver = fakeResolver{
	folders: map[string]string{
		"{6D809377-6AF0-444B-8957-A3773F02200E}": `C:\Program Files`,
		"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}": `C:\WINDOWS\system32`,
	},
	shortcuts: map[string]string{
		"microsoft edge": `C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe`,
		"word":           `C:\Program Files\Microsoft Office\root\Office16\WINWORD.EXE`,
		"some website":   `C:\Users\me\site.url`,
	},
}

func TestFromProcess(t *testing.T) {
	if id := FromProcess(`C:\Program Files\Google\Chrome\Application\chrome.exe`, ""); id != "chrome.exe" {
		t.Errorf("unpackaged: %s", id)
	}
	if id := FromProcess(`C:\Users\me\AppData\Local\Programs\Microsoft VS Code\Code.exe`, ""); id != "code.exe" {
		t.Errorf("lowercase: %s", id)
	}
	if id := FromProcess(`C:\Program Files\WindowsApps\MSTeams_25.1_x64__8wekyb3d8bbwe\ms-teams.exe`, "MSTeams_8wekyb3d8bbwe"); id != "MSTeams_8wekyb3d8bbwe" {
		t.Errorf("packaged: the family as given: %s", id)
	}
	if ExeName(`C:\x\Code.exe`) != "Code" || ExeName("notepad") != "notepad" {
		t.Error("ExeName")
	}
}

func TestFromStartApp(t *testing.T) {
	cases := []struct {
		app  StartApp
		id   string
		path string
	}{
		// 1. A packaged app's AppUserModelID: the family.
		{StartApp{"Calculator", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"}, "Microsoft.WindowsCalculator_8wekyb3d8bbwe", ""},
		{StartApp{"Microsoft Teams", "MSTeams_8wekyb3d8bbwe!MSTeams"}, "MSTeams_8wekyb3d8bbwe", ""},
		// 2. A path to an exe, from a known folder.
		{StartApp{"Google Chrome", `{6D809377-6AF0-444B-8957-A3773F02200E}\Google\Chrome\Application\chrome.exe`}, "chrome.exe", `C:\Program Files\Google\Chrome\Application\chrome.exe`},
		{StartApp{"Command Prompt", `{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\cmd.exe`}, "cmd.exe", `C:\WINDOWS\system32\cmd.exe`},
		{StartApp{"Tool", `{00000000-0000-0000-0000-000000000000}\Tool\TOOL.EXE`}, "tool.exe", ""},
		{StartApp{"Abs", `D:\Apps\Abs.exe`}, "abs.exe", `D:\Apps\Abs.exe`},
		// 3. Anything else: the shortcut of that name.
		{StartApp{"Microsoft Edge", "MSEdge"}, "msedge.exe", `C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe`},
		{StartApp{"Word", "Microsoft.Office.WINWORD.EXE.15"}, "winword.exe", `C:\Program Files\Microsoft Office\root\Office16\WINWORD.EXE`},
		// Windows' own: File Explorer.
		{StartApp{"File Explorer", "Microsoft.Windows.Explorer"}, "explorer.exe", ""},
		// 4. Nothing resolves (a shortcut to a web page, an unknown id).
		{StartApp{"Some website", "Microsoft.AutoGenerated.{ABC}"}, "startapp:Microsoft.AutoGenerated.{ABC}", ""},
		{StartApp{"Control Panel", "Microsoft.Windows.ControlPanel"}, "startapp:Microsoft.Windows.ControlPanel", ""},
	}
	for _, c := range cases {
		id, path := FromStartApp(c.app, resolver)
		if id != c.id || path != c.path {
			t.Errorf("%v: %q %q, want %q %q", c.app, id, path, c.id, c.path)
		}
	}
	// Without a resolver the rules that need none still hold.
	if id, _ := FromStartApp(StartApp{"Edge", "MSEdge"}, nil); id != "startapp:MSEdge" {
		t.Errorf("no resolver: %s", id)
	}
}

func TestParseStartApps(t *testing.T) {
	apps, err := ParseStartApps([]byte("\xEF\xBB\xBF[{\"Name\":\"Calculator\",\"AppID\":\"Microsoft.WindowsCalculator_8wekyb3d8bbwe!App\"},{\"Name\":\"Nothing\",\"AppID\":\"\"},{\"Name\":\" Ünïcode \",\"AppID\":\"x!y\"}]\r\n"))
	if err != nil || len(apps) != 2 || apps[0].Name != "Calculator" || apps[1].Name != "Ünïcode" {
		t.Errorf("array: %v %v", apps, err)
	}
	one, err := ParseStartApps([]byte(`{"Name":"Only","AppID":"only.exe"}`))
	if err != nil || len(one) != 1 || one[0].AppID != "only.exe" {
		t.Errorf("a single object: %v %v", one, err)
	}
	if none, err := ParseStartApps([]byte("  \r\n")); err != nil || len(none) != 0 {
		t.Errorf("nothing: %v %v", none, err)
	}
	if _, err := ParseStartApps([]byte("Get-StartApps : not recognized")); err == nil {
		t.Error("an error message isn't JSON")
	}
}

func TestIndexKeepsTheFirstEntryPerID(t *testing.T) {
	apps := []StartApp{
		{"Google Chrome", `{6D809377-6AF0-444B-8957-A3773F02200E}\Google\Chrome\Application\chrome.exe`},
		{"Work - Chrome", `{6D809377-6AF0-444B-8957-A3773F02200E}\Google\Chrome\Application\CHROME.EXE`},
		{"Calculator", "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},
	}
	index := Index(apps, resolver)
	if len(index) != 2 || index[0].ID != "chrome.exe" || index[0].Name != "Google Chrome" || index[0].AppID != apps[0].AppID {
		t.Errorf("index: %+v", index)
	}
}

func TestMerge(t *testing.T) {
	running := []Running{
		{ID: "chrome.exe", Name: "Google Chrome", Path: `C:\chrome.exe`, PID: 10, Active: true},
		{ID: "chrome.exe", Name: "Google Chrome", PID: 11},
		{ID: "MSTeams_8wekyb3d8bbwe", Name: "Microsoft Teams", PID: 12, Hidden: true},
	}
	installed := []Installed{
		{ID: "chrome.exe", Name: "Chrome (Start)", AppID: "Chrome", Path: `C:\installed\chrome.exe`},
		{ID: "mSTeams_8wekyb3d8bbwe", Name: "Teams", AppID: "MSTeams_8wekyb3d8bbwe!MSTeams"},
		{ID: "Microsoft.WindowsCalculator_8wekyb3d8bbwe", Name: "Calculator", AppID: "Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"},
	}
	apps := Merge(running, installed)
	var ids []string
	for _, a := range apps {
		ids = append(ids, a.ID)
	}
	if !reflect.DeepEqual(ids, []string{"Microsoft.WindowsCalculator_8wekyb3d8bbwe", "chrome.exe", "MSTeams_8wekyb3d8bbwe"}) {
		t.Fatalf("ids (by name): %v", ids)
	}
	calc, chrome, teams := apps[0], apps[1], apps[2]
	if chrome.PID == nil || *chrome.PID != 10 || !chrome.Active || !chrome.Running || chrome.Name != "Google Chrome" || *chrome.Path != `C:\chrome.exe` {
		t.Errorf("chrome: running wins: %+v", chrome)
	}
	if !teams.Hidden || teams.ID != "MSTeams_8wekyb3d8bbwe" {
		t.Errorf("teams: the running id: %+v", teams)
	}
	if calc.Running || calc.PID != nil || calc.Active || calc.Path != nil || calc.Category != nil {
		t.Errorf("calculator isn't running: %+v", calc)
	}
	if only := Merge(running, nil); len(only) != 2 {
		t.Errorf("running only: %v", only)
	}
}

func TestNames(t *testing.T) {
	if n := Name("Notepad++", "", "Notepad++ : a free (GNU) source code editor", `C:\npp\notepad++.exe`); n != "Notepad++" {
		t.Errorf("the Start menu name first: %s", n)
	}
	if n := Name("", "", "Google Chrome", `C:\chrome.exe`); n != "Google Chrome" {
		t.Errorf("FileDescription: %s", n)
	}
	if n := Name("", "", " ", `C:\x\Tool.exe`); n != "Tool" {
		t.Errorf("exe name: %s", n)
	}
	if n := Name("", "MSTeams_8wekyb3d8bbwe", "Microsoft Teams", `C:\ms-teams.exe`); n != "MSTeams_8wekyb3d8bbwe" {
		t.Errorf("a packaged app without a Start menu name: %s", n)
	}
	if n := Clip(strings.Repeat("x", 300), "id"); len(n) != 200 {
		t.Errorf("clip: %d", len(n))
	}
	if n := Clip("  ", "the.id"); n != "the.id" {
		t.Errorf("fallback: %s", n)
	}
}

func TestBaseName(t *testing.T) {
	for in, want := range map[string]string{`C:\a\b.exe`: "b.exe", "c/d.exe": "d.exe", "e.exe": "e.exe"} {
		if got := BaseName(in); got != want {
			t.Errorf("%s: %s", in, got)
		}
	}
}

func TestShortcuts(t *testing.T) {
	if a, ok := FromShortcut("Microsoft Edge", `C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe`); !ok || a.ID != "msedge.exe" || a.Name != "Microsoft Edge" || a.AppID != "" {
		t.Errorf("edge: %+v %v", a, ok)
	}
	for _, c := range [][2]string{
		{"Uninstall Foo", `C:\Foo\uninst.exe`},
		{"Foo", `C:\Foo\unins000.exe`},
		{"Docs", `C:\Foo\readme.html`},
	} {
		if _, ok := FromShortcut(c[0], c[1]); ok {
			t.Errorf("%v isn't an app", c)
		}
	}
	list := AppendNew([]Installed{{ID: "msedge.exe", Name: "Edge (Start)", AppID: "MSEdge"}}, []Installed{{ID: "MSEDGE.EXE", Name: "Microsoft Edge"}, {ID: "notepad.exe", Name: "Notepad"}})
	if len(list) != 2 || list[0].AppID != "MSEdge" || list[1].ID != "notepad.exe" {
		t.Errorf("AppendNew: %+v", list)
	}
}

